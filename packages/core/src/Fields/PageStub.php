<?php

declare(strict_types=1);

namespace LynxCms\Core\Fields;

use LynxCms\Core\Models\Field;
use LynxCms\Core\Models\Template;
use LynxCms\Core\Pages\PageArray;
use LynxCms\Core\Pages\TranslatableValue;

/**
 * A PHPStan stub for the Page class with one property per field of the schema, so code that
 * reads $page->starts_on is checked against what the field type returns. Writes accept anything,
 * as pages.save validates them.
 *
 * @internal
 */
final class PageStub
{
    /** Magic properties every page has, besides its fields. */
    private const array BUILT_IN = [
        'name' => 'string',
        'url' => 'string',
        'path' => 'string|null',
        'template' => Template::class,
        'parent' => '\LynxCms\Core\Pages\Page|null',
        'children' => PageArray::class,
    ];

    public function render(): string
    {
        $lines = [];

        foreach (self::BUILT_IN as $name => $type) {
            $lines[] = " * @property-read {$type} \${$name}";
        }

        foreach (lynx()->fields->all() as $field) {
            $lines[] = " * @property-read {$this->type($field)} \${$field->name}";
            $lines[] = " * @property-write mixed \${$field->name}";
        }

        return implode("\n", [
            '<?php',
            '',
            '// Generated by `php artisan lynx:phpstan-stub` from the Lynx schema. Regenerate it after',
            '// adding fields; add it to stubFiles in phpstan.neon. Reading a field the page\'s template',
            '// does not have returns null.',
            '',
            'namespace LynxCms\Core\Pages;',
            '',
            '/**',
            ...$lines,
            ' */',
            'class Page implements \JsonSerializable',
            '{',
            '}',
            '',
        ]);
    }

    private function type(Field $field): string
    {
        if ($field->isTranslatable()) {
            return '\\'.TranslatableValue::class;
        }

        $type = $field->fieldType();

        return $type instanceof DescribesPhpType ? $type->phpType($field) : 'mixed';
    }
}
