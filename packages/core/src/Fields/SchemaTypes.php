<?php

declare(strict_types=1);

namespace LynxCms\Core\Fields;

use LynxCms\Core\Models\Field;
use LynxCms\Core\Models\Template;
use LynxCms\Core\Pages\Page;
use LynxCms\Core\Pages\PageArray;
use LynxCms\Core\Pages\TranslatableValue;

/**
 * The PHP type of every field as templates read it, for PHPStan (ADR-0083): lynx:phpstan writes
 * them to a file that Lynx's PHPStan extension reads, so $page->starts_on and $item->role are
 * checked against what their field type returns. Writes accept anything, as pages.save validates
 * them. Types are fully qualified, for PHPStan to resolve without a namespace.
 *
 * @internal
 */
final class SchemaTypes
{
    /** Magic properties every page has besides its fields: type, and whether code may set it. */
    private const array PAGE_BUILT_IN = [
        'name' => ['string', true],
        'url' => ['string', false],
        'path' => ['string|null', false],
        'template' => ['\\'.Template::class, false],
        'parent' => ['\\'.Page::class.'|null', false],
        'children' => ['\\'.PageArray::class, false],
    ];

    /** Magic properties every repeater or matrix item has besides its fields. */
    private const array ITEM_BUILT_IN = [
        'key' => ['string', false],
    ];

    /**
     * @return array{page: array<string, array{type: string, writable: bool}>, item: array<string, array{type: string, writable: bool}>}
     */
    public function all(): array
    {
        $fields = [];

        foreach (lynx()->fields->all() as $field) {
            $fields[(string) $field->name] = ['type' => $this->type($field), 'writable' => true];
        }

        return [
            'page' => $this->builtIn(self::PAGE_BUILT_IN) + $fields,
            'item' => $this->builtIn(self::ITEM_BUILT_IN) + $fields,
        ];
    }

    /** The file lynx:phpstan writes: a PHP array PHPStan's extension includes. */
    public function render(): string
    {
        return "<?php\n\n// Generated by `php artisan lynx:phpstan` from the Lynx schema; regenerate it after changing\n"
            ."// fields. Lynx's PHPStan extension (vendor/lynxcms/core/phpstan/extension.neon) reads it.\n\n"
            .'return '.var_export($this->all(), true).";\n";
    }

    /**
     * @param  array<string, array{0: string, 1: bool}>  $properties
     * @return array<string, array{type: string, writable: bool}>
     */
    private function builtIn(array $properties): array
    {
        return array_map(fn (array $property): array => ['type' => $property[0], 'writable' => $property[1]], $properties);
    }

    private function type(Field $field): string
    {
        if ($field->isTranslatable()) {
            return '\\'.TranslatableValue::class;
        }

        $type = $field->fieldType();

        return $type instanceof DescribesPhpType ? $type->phpType($field) : 'mixed';
    }
}
